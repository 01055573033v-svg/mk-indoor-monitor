//    달력에 적힌 「자전거 n」 총 시간과 맞는지 시험에서 확인한다(웨이트·평롤러·와트바이크·르몽드 부분은 로라 세션 밖).
// 엑셀을 바꾸면 이 파일도 손으로 맞춰야 한다(앱은 엑셀을 직접 읽지 않음 — 업무실 밖 공개 앱이라 원본을 싣지 않는다).
// W-up 「50→75%FTP」처럼 올라가는 구간은 50~75 범위로, 쿨다운·스핀업·스프린트·공격처럼 %FTP가 없는 구간은 목표 없음(자유)으로 둔다.
// 역치(THR)는 시트에 %FTP가 없어 이 앱 존 경계(zones.js, V2 lib/ftp.ts 와 같음)의 역치 존 91~105 를 쓴다.

const s = (label, min, lo = null, hi = null) => ({ label, sec: Math.round(min * 60), lo, hi });
const Z2 = [56, 75];
const reps = (n, work, rest, { lastRest = true } = {}) =>
  Array.from({ length: n }, (_, i) => [{ ...work, label: `${work.label} ${i + 1}/${n}` }, ...(i < n - 1 || lastRest ? [rest] : [])]).flat();

const GROUP_NAME = { '중': ['중E', '중S'], '고E': ['고E'], '고S': ['고S'], '전체': [] };
const SECTION = { '고E': '고등 E', '중': '중등 E·S', '고S': '고등 S', '전체': '전체 · 회복 주 · Z2' };
/** group: 화면 이름 앞 글자이자 세션 시작 때 고를 대상 그룹 기본값(중 = 중E·중S). section: 고르기 목록의 묶음. */
const team = (id, group, name, source, steps) => ({ id, groups: GROUP_NAME[group], section: SECTION[group], name: `[${group === '중' ? '중등' : group}] ${name}`, source, steps });

/** Z2 연속(12/02·12/06 세부표 틀): 1h15m 까지는 W-up 10 · Z2 60~70 · 쿨다운 5, 1h30m 이상은 W-up 15 · 쿨다운 10(12/05 세부표). */
const z2 = min => min >= 90 ? [s('W-up', 15), s('Z2', min - 25, 60, 70), s('쿨다운', 10)] : [s('W-up', 10), s('Z2', min - 15, 60, 70), s('쿨다운', 5)];
const hm = min => `${Math.floor(min / 60) ? `${Math.floor(min / 60)}h` : ''}${min % 60 ? `${min % 60}m` : ''}`;
/** 스핀업 N×8s(SPIN, 11/17·12/01 세부표): W-up 10 → 8s 최대 회전 · 사이 1m30s 아주 가볍게. 목표는 rpm(160+)이라 와트 목표 없음. */
const spin = n => [s('W-up', 10, 50, 65), ...reps(n, s('스핀업 160rpm+', 8 / 60), s('가볍게', 1.5), { lastRest: false })];
/** Z2 + 케이던스 단계(11/29 세부표): 90→105→120rpm 각 3m×2 (Z2 파워), 이어서 Z2, 쿨다운 5. */
const cadenceLadder = min => [s('W-up', 10),
  ...['90', '90', '105', '105', '120', '120'].map(r => s(`${r}rpm (Z2 파워)`, 3, ...Z2)), s('Z2', min - 33, 60, 70), s('쿨다운', 5)];
/** 중등 Z2 + 110rpm 3×5m(11/18·11/25 세부표): W-up 10 · Z2 10 · (110rpm 5m · Z2 3m)×3 · Z2 · 쿨다운 5. */
const z2With110 = min => [s('W-up', 10), s('Z2', 10, 60, 70), ...reps(3, s('110rpm (Z2 파워)', 5, ...Z2), s('Z2', 3, ...Z2), { lastRest: false }),
  s('Z2', min - 46, 60, 70), s('쿨다운', 5)];
/** 토요일 ITT(12/12 달력, 11/21 세부표 강도): W-up 15 · ITT 3×10m 100~110%FTP · 사이 10m Z2 · 이어서 Z2. */
const itt = z2min => [s('W-up', 15, 50, 70), ...reps(3, s('ITT', 10, 100, 110), s('Z2', 10, ...Z2), { lastRest: false }), s('Z2', z2min, ...Z2)];

